async function http(url, options = {}) {
  const response = await fetch(new URL(url, base), {...options, redirect: 'manual', headers: {...options.headers, Cookie: cookie}});
  const setCookie = response.headers.getSetCookie();
  if (setCookie.length) cookie = setCookie.map(value => value.split(';')[0]).join('; ');
  return response;
}
const token = html => html.match(/name="csrf" value="([^"]+)"/)?.[1] || '';
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(fn, message) {
  const deadline = Date.now() + 5000;
  while (Date.now() < deadline) { if (fn()) return; await wait(15); }
  throw new Error(message);
}
function createPage(html, url) {
  const virtualConsole = new VirtualConsole();
  virtualConsole.on('jsdomError', error => errors.push(error.message));
  const dom = new JSDOM(html, {url, runScripts: 'outside-only', pretendToBeVisual: true, virtualConsole});
  const {window} = dom;
  for (const file of ['app.css', 'calendar.css']) {
    const style = window.document.createElement('style');
    style.textContent = fs.readFileSync(path.join(__dirname, '../css', file), 'utf8');
    window.document.head.append(style);
  }
  window.fetch = (url, options) => http(url, options);
  window.AbortController = AbortController;
  window.HTMLDialogElement.prototype.showModal = function() { this.open = true; };
  window.HTMLFormElement.prototype.submit = function() { submitted = new URLSearchParams([...new window.FormData(this)]); };
  window.eval(fs.readFileSync(path.join(__dirname, '../js/app.js'), 'utf8'));
  window.eval(fs.readFileSync(path.join(__dirname, '../js/calendar.js'), 'utf8'));
  return dom;
}
